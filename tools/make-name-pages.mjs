function sitemap(names) {
  const seen = new Set(ORIGINAL_SITEMAP_ENTRIES.map(([loc]) => loc));
  const rows = [...ORIGINAL_SITEMAP_ENTRIES];
  const push = (loc, priority, changefreq, lastmod) => {
    if (seen.has(loc)) return;
    seen.add(loc);
    rows.push([loc, priority, changefreq, lastmod]);
  };
  push("/names", "0.8", "weekly", LASTMOD);
  for (const entry of names) push(`/${entry.slug}`, "0.7", "monthly", LASTMOD);
  const body = rows
    .map(([loc, priority, changefreq, lastmod]) =>
      `  <url><loc>${SITE}${loc}</loc><lastmod>${lastmod}</lastmod><changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`)
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

// Add the Chinese name, pinyin, a small English+Chinese sample and a price line
// to a page that already exists. Everything already on the page is kept: the
// title, the H1, the body copy, the canonical, the og:image and the analytics
// script. Only the four things named above are inserted — the hand-written copy
// is never rewritten, so a re-run is a no-op once the insertions are present.
function patchExisting(entry) {
  const file = path.join(ROOT, `${entry.slug}.html`);
  let html = fs.readFileSync(file, "utf8");
  const original = html;
  const alt = altFor(entry);
  const img = imageFileFor(entry.slug);

  if (!html.includes("<!-- name-combo -->")) {
    const caption = html.match(/^.*<p class="caption">[\s\S]*?<\/p>\n/m);
    if (!caption) throw new Error(`${entry.slug}.html: could not find the caption to insert after`);
    const figure =
      `\n      <!-- name-combo -->\n` +
      `      <figure class="sample">\n` +
      `        <img src="${IMG_DIR}/${img}" width="480" height="640" alt="${escapeHtml(alt)}" />\n` +
      `        <figcaption>\n` +
      `          <span class="sample-badge">Sample</span>\n` +
      `          <strong>${escapeHtml(entry.name)} + ${escapeHtml(entry.zh)}</strong>\n` +
      `          <span>Pinyin: ${escapeHtml(entry.pinyin)}. Transliteration by sound, not by meaning — have a person review it before permanent use.</span>\n` +
      `        </figcaption>\n` +
      `      </figure>\n`;
    html = html.replace(caption[0], `${caption[0]}${figure}`);
  }

  if (!html.includes(PRICE_LABEL)) {
    const cta = html.indexOf('      <a class="cta"');
    if (cta < 0) throw new Error(`${entry.slug}.html: could not find the CTA to insert the price before`);
    const price =
      `      <p class="hint price">Free watermarked preview. ${PRICE_LABEL} once for a clean ` +
      `high-resolution download of this name in every style and setting. No subscription. ` +
      `Digital product, delivered instantly; see <a href="terms">Terms</a>.</p>\n\n`;
    html = `${html.slice(0, cta)}${price}${html.slice(cta)}`;
  }

  if (html !== original) {
    fs.writeFileSync(file, html);
    return true;
  }
  return false;
}

function main() {
  const names = loadNames();
  if (names.length < 100) throw new Error(`only ${names.length} names in ${NAMES_FILE}`);
  const slugs = new Set(names.map((entry) => entry.slug));
  if (slugs.size !== names.length) throw new Error("two names collapse onto one slug");

  const conflicts = names.filter((entry) => RESERVED_SLUGS.has(entry.slug));
  const pages = names.filter((entry) => !RESERVED_SLUGS.has(entry.slug));

  let written = 0;
  let patched = 0;
  pages.forEach((entry, index) => {
    if (EXISTING_NAME_PAGES.includes(entry.slug)) {
      if (patchExisting(entry)) patched += 1;
      return;
    }
    const prev = pages[(index - 1 + pages.length) % pages.length];
    const next = pages[(index + 1) % pages.length];
    const file = path.join(ROOT, `${entry.slug}.html`);
    if (fs.existsSync(file)) {
      const existing = fs.readFileSync(file, "utf8");
      if (!existing.includes(MARKER)) {
        throw new Error(`${entry.slug}.html exists but was not generated by this script; refusing to overwrite it`);
      }
    }
    fs.writeFileSync(file, namePage(entry, prev, next));
    written += 1;
  });

  fs.writeFileSync(path.join(ROOT, "names.html"), namesIndex(pages));
  fs.writeFileSync(path.join(ROOT, "sitemap.xml"), sitemap(pages));
  console.log(`wrote ${written} new name pages, patched ${patched} existing name pages`);
  console.log(`wrote names.html (${pages.length} names) and sitemap.xml`);
  if (conflicts.length) {
    console.log(`skipped ${conflicts.length} names that collide with an existing page:`);
    for (const entry of conflicts) console.log(`  ${entry.name} -> /${entry.slug}`);
  } else {
    console.log("skipped 0 names: no table name collides with an existing page");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
