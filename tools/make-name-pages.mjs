const NAMES_FILE = path.join(ROOT, "data", "names-zh.json");
const IMG_DIR = "samples";
const PIN_DIR = "pins";
const MARKER = "<!-- generated by tools/make-name-pages.mjs -->";
const LASTMOD = "2026-10-04";

// Root slugs that are real pages but not names: a table name that lands on one
// of these is skipped, so a generated name page can never shadow love/peace/
// hope/dream, the guides, or the legal pages.
