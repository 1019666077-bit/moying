#!/usr/bin/env node
/**
 * Generate one rich page per English name from data/names-zh.json, at the root.
 *
 *   node tools/build-names-data.mjs   # (re)build data/names-zh.json
 *   node tools/make-name-pages.mjs    # write <slug>.html, names.html, sitemap.xml
 *
 * Reads data/names-zh.json (name -> { zh, pinyin, gender, origin, meaning, note })
 * and writes:
 *   <slug>.html        one page per name, e.g. noah.html -> /noah
 *   names.html         the /names index listing every name grouped A–Z
 *   sitemap.xml        the original entries plus /names and every name page
 *
 * The URL scheme is deliberate: the eight landing pages already indexed by
 * Google (emma, michael, sophia, james, grace, lily, ethan, olivia) live at the
 * root and are served at /<name>. New pages keep that same flat single-segment
 * shape, so existing URLs never change. The eight pages are regenerated here too,
 * so every name page carries the same full content (characters, meanings, origin,
 * a short note and a clear path into the generator); their URLs and canonicals
 * are unchanged. Non-name pages (love/peace/hope/dream, guides, legal) are never
 * touched.
 *
 * Each page is a static watermarked sample image (samples/) plus unique copy,
 * six related-name links, and a CTA that opens the generator prefilled. The price
 * comes from the same functions/lib/pricing.js constant the checkout uses.
 */
