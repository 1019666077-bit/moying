export function slugFor(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

export function imageFileFor(slug) {
  return `${slug}-chinese-calligraphy-name.jpg`;
}

export function loadNames() {
  const table = JSON.parse(fs.readFileSync(NAMES_FILE, "utf8"));
  const records = table.names || table;
  const charMeanings = table._charMeanings || {};
  const names = [];
  for (const [name, value] of Object.entries(records)) {
    if (name.startsWith("_")) continue;
    const zh = value && typeof value === "object" ? value.zh : value;
    if (typeof zh !== "string" || !zh) continue;
    const pinyin = (value && typeof value === "object" && value.pinyin) || "";
    const syllables = pinyin ? pinyin.split(/\s+/) : [];
    const chars = [...zh].map((ch, i) => ({
      ch,
      py: syllables[i] || "",
      mean: charMeanings[ch] || "",
    }));
    names.push({
      name,
      slug: slugFor(name),
      zh,
      pinyin,
      gender: value.gender || "u",
      origin: value.origin || "",
      meaning: value.meaning || "",
      note: value.note || "",
      chars,
    });
  }
  return names;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function hash(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) | 0;
  return Math.abs(h);
}

function pick(arr, key) {
  return arr[hash(key) % arr.length];
}

// "a" vs "an" for a word, accounting for the few vowel-written names that begin
// with a "y" sound (Eugene) — everything else follows the first letter.
function aAn(word) {
  const w = String(word || "");
  if (/^(eu|ew)/i.test(w)) return "a";
  return /^[aeiou]/i.test(w) ? "an" : "a";
}

// A Pinterest-sized og:image exists for a handful of names; fall back to the
// in-page sample for everyone else.
function ogImageFor(slug) {
  const pin = path.join(ROOT, PIN_DIR, imageFileFor(slug));
  if (fs.existsSync(pin)) {
    return { url: `${SITE}/${PIN_DIR}/${imageFileFor(slug)}`, width: 1000, height: 1500 };
  }
  return { url: `${SITE}/${IMG_DIR}/${imageFileFor(slug)}`, width: 480, height: 640 };
}

function altFor(entry) {
  return `${entry.name} written in Chinese brush calligraphy style with Chinese name ${entry.zh}`;
}

// Pick ~6 related names: same initial first, then same gender, then same origin.
// Unisex names match either gender.
function relatedFor(entry, names) {
  const sameInitial = (a) => a.name[0].toLowerCase() === entry.name[0].toLowerCase();
  const sameGender = (a) => entry.gender === "u" || a.gender === "u" || a.gender === entry.gender;
  const scored = names
    .filter((a) => a.slug !== entry.slug)
    .map((a) => {
      let score = 0;
      if (sameInitial(a)) score += 3;
      if (sameGender(a)) score += 2;
      if (a.origin && a.origin === entry.origin) score += 1;
      return { a, score };
    })
    .sort((x, y) => (y.score - x.score) || x.a.name.localeCompare(y.a.name));
  return scored.slice(0, 6).map((x) => x.a);
}

