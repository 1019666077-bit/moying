function sitemap(names) {
  const seen = new Set(ORIGINAL_SITEMAP_ENTRIES.map(([loc]) => loc));
  const rows = [...ORIGINAL_SITEMAP_ENTRIES];
  const push = (loc, priority, changefreq, lastmod) => {
    if (seen.has(loc)) return;
    seen.add(loc);
    rows.push([loc, priority, changefreq, lastmod]);
  };
  push("/names", "0.8", "weekly", LASTMOD);
  for (const entry of names) push(`/${entry.slug}`, "0.7", "monthly", LASTMOD);
  const body = rows
    .map(
      ([loc, priority, changefreq, lastmod]) =>
        `  <url><loc>${SITE}${loc}</loc><lastmod>${lastmod}</lastmod><changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`
    )
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

function main() {
  const names = loadNames();
  if (names.length < 200) throw new Error(`only ${names.length} names in ${NAMES_FILE}`);
  const slugs = new Set(names.map((entry) => entry.slug));
  if (slugs.size !== names.length) throw new Error("two names collapse onto one slug");

  const conflicts = names.filter((entry) => RESERVED_SLUGS.has(entry.slug));
  const pages = names.filter((entry) => !RESERVED_SLUGS.has(entry.slug));

  let written = 0;
  for (const entry of pages) {
    const file = path.join(ROOT, `${entry.slug}.html`);
    fs.writeFileSync(file, namePage(entry, pages));
    written += 1;
  }

  fs.writeFileSync(path.join(ROOT, "names.html"), namesIndex(pages));
  fs.writeFileSync(path.join(ROOT, "sitemap.xml"), sitemap(pages));
  console.log(`wrote ${written} name pages`);
  console.log(`wrote names.html (${pages.length} names, ${new Set(pages.map((n) => n.name[0].toUpperCase())).size} letters) and sitemap.xml`);
  if (conflicts.length) {
    console.log(`skipped ${conflicts.length} names that collide with an existing page:`);
    for (const entry of conflicts) console.log(`  ${entry.name} -> /${entry.slug}`);
  } else {
    console.log("skipped 0 names: no table name collides with an existing page");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
